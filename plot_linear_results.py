import matplotlib.pyplot as plt
import numpy as np

from closure_evaluation import load_results


plt.rcParams["mathtext.fontset"] = "stix"
plt.rcParams["font.family"] = "serif"
plt.rcParams.update(
    {
        "font.size": 14,
        "axes.labelsize": 16,
        "axes.titlesize": 16,
        "legend.fontsize": 12.5,
        "xtick.labelsize": 12.5,
        "ytick.labelsize": 12.5,
    }
)


def _posterior_closure_samples_linear(data: dict, item: dict) -> np.ndarray:
    """Return posterior samples of E[G|theta,x] on the training window.

    For the linear slow-fast problem the closure library is degree-1 in the
    resolved scalar x, i.e. [1, x].  The saved FeatureScaler is applied exactly
    as it was during inference.  Only coefficient uncertainty is propagated
    here; the saved likelihood sigma is *not* added, so the band represents
    uncertainty in the inferred closure function itself rather than noisy
    posterior observations.

    Returns
    -------
    samples : ndarray, shape (n_posterior_samples, n_training_times)
    """
    x_train = np.asarray(data["x_train"], dtype=float)
    if x_train.ndim != 2 or x_train.shape[1] != 1:
        raise ValueError(
            "The linear plotting script expects one resolved state in x_train."
        )

    posterior = item["posterior"]
    beta = np.asarray(posterior["beta"], dtype=float)
    if beta.ndim == 1:
        beta = beta[None, :]

    # The linear closure library is [1, x].
    design = np.column_stack((np.ones(x_train.shape[0]), x_train[:, 0]))

    scaler = item.get("scaler", None)
    if scaler is not None:
        mean = np.asarray(scaler.mean, dtype=float)
        scale = np.asarray(scaler.scale, dtype=float)
        scale = np.where(np.abs(scale) > 0.0, scale, 1.0)
        design = (design - mean) / scale

    if design.shape[1] != beta.shape[1]:
        raise ValueError(
            "Saved posterior coefficient dimension does not match the expected "
            f"linear design matrix: {beta.shape[1]} vs {design.shape[1]}."
        )

    # design: (nt, ncoef), beta.T: (ncoef, nsamples)
    return (design @ beta.T).T


def _credible_interval(samples: np.ndarray, mass: float = 0.95):
    """Posterior mean and equal-tailed credible interval."""
    if not (0.0 < mass < 1.0):
        raise ValueError("mass must lie between 0 and 1.")
    alpha = 0.5 * (1.0 - mass)
    mean = np.mean(samples, axis=0)
    lower = np.quantile(samples, alpha, axis=0)
    upper = np.quantile(samples, 1.0 - alpha, axis=0)
    return mean, lower, upper


def _common_pdf_curves(x_truth: np.ndarray, x_model: np.ndarray, bins: int = 60):
    """Compute comparable density histograms on a common support."""
    truth = np.asarray(x_truth, dtype=float).ravel()
    model = np.asarray(x_model, dtype=float).ravel()
    both = np.concatenate((truth, model))

    lo, hi = np.nanmin(both), np.nanmax(both)
    if not np.isfinite(lo) or not np.isfinite(hi):
        raise ValueError("Non-finite data encountered while constructing PDF.")
    if np.isclose(lo, hi):
        pad = max(abs(lo), 1.0) * 1.0e-6
        lo, hi = lo - pad, hi + pad

    edges = np.linspace(lo, hi, bins + 1)
    centers = 0.5 * (edges[:-1] + edges[1:])
    p_truth, _ = np.histogram(truth, bins=edges, density=True)
    p_model, _ = np.histogram(model, bins=edges, density=True)
    return centers, p_truth, p_model


def _print_metric_summary(best: dict, best_test: dict | None) -> None:
    """Print the compact verification table used in the manuscript."""
    ev = best["evaluation"]
    closure = ev["closure"]
    calibration = ev["calibration"]
    short = ev["short_time"]

    print("\nLinear slow-fast verification metrics")
    print("-" * 68)
    print(f"{'Metric':<38}{'Linear closure':>28}")
    print("-" * 68)
    print(f"{'Closure NRMSE':<38}{closure['nrmse_std']:>28.6e}")
    print(f"{'Closure R^2':<38}{closure['r2']:>28.10f}")
    print(f"{'Closure correlation':<38}{closure['corr']:>28.10f}")
    print(
        f"{'95% predictive coverage':<38}"
        f"{calibration['empirical_coverage']:>28.4f}"
    )
    print(
        f"{'A-posteriori mean normalized error':<38}"
        f"{short['mean_normalized_error']:>28.6e}"
    )
    print(
        f"{'A-posteriori max normalized error':<38}"
        f"{short['max_normalized_error']:>28.6e}"
    )
    print(
        f"{'Forecast horizon':<38}"
        f"{short['forecast_horizon']:>28.6f}"
    )

    if best_test is not None:
        test_ev = best_test["evaluation"]
        print("-" * 68)
        print("Independent-trajectory checks")
        print(
            f"{'Closure NRMSE':<38}"
            f"{test_ev['closure']['nrmse_std']:>28.6e}"
        )
        print(
            f"{'Mean normalized state error':<38}"
            f"{test_ev['short_time']['mean_normalized_error']:>28.6e}"
        )
        print(
            f"{'PDF Wasserstein distance':<38}"
            f"{test_ev['long_time']['pdf_wasserstein']:>28.6e}"
        )
        print(
            f"{'log-PSD RMSE':<38}"
            f"{test_ev['long_time']['log_psd_rmse']:>28.6e}"
        )
    print("-" * 68)


def plot_linear_results(
    filename: str = "closure_analysis_results_linear.pkl",
    state_index: int = 0,
    credible_mass: float = 0.95,
    save_figure: bool = True,
    output_name: str = "figure_linear_bayesian_closure_verification.png",
):
    data = load_results(filename)

    display_name = data.get("display_name", "Linear slow-fast system")
    state_labels = data.get("state_labels", [r"$x$"])
    closure_label = data.get("closure_label", r"$G$")

    t = np.asarray(data["t"])
    x_true = np.asarray(data["x_true"])
    t_train = np.asarray(data["t_train"])
    g_train = np.asarray(data["g_train"])
    results = data["results"]

    t_test = np.asarray(data["t_test"])
    x_true_test = np.asarray(data["x_true_test"])
    test_results = data["test_results"]

    if not results:
        raise RuntimeError("No successful training models are stored in this file.")

    state_index = int(state_index)
    if state_index < 0 or state_index >= x_true.shape[1]:
        raise ValueError(
            f"state_index={state_index} is invalid for {x_true.shape[1]} states."
        )
    state_label = (
        state_labels[state_index]
        if state_index < len(state_labels)
        else f"state {state_index + 1}"
    )

    # Select the model using TRAINING closure performance only.
    best = min(results, key=lambda item: item["evaluation"]["closure"]["nrmse_std"])

    best_test = next(
        (item for item in test_results if item["spec"].name == best["spec"].name),
        None,
    )

    # ------------------------------------------------------------------
    # Posterior uncertainty of the inferred closure function.
    # ------------------------------------------------------------------
    closure_samples = _posterior_closure_samples_linear(data, best)
    g_post_mean, g_lo, g_hi = _credible_interval(closure_samples, credible_mass)

    closure_component = 0

    # ------------------------------------------------------------------
    # Figure 2: four-panel manuscript figure.
    # ------------------------------------------------------------------
    fig, axes = plt.subplots(2, 2, figsize=(14.5, 10.5), constrained_layout=False)
    ax_a, ax_b, ax_c, ax_d = axes.ravel()

    # (a) True/recovered target vs posterior closure mean + credible band.
    ax_a.plot(
        t_train,
        g_train[:, closure_component],
        "k--",
        lw=2,
        label="Closure target",
    )
    ax_a.plot(
        t_train,
        g_post_mean,
        lw=2,
        label=r"Posterior mean $E[\widehat{G}\mid\mathcal{D}]$",
    )
    coverage_pct = int(round(100.0 * credible_mass))
    ax_a.fill_between(
        t_train,
        g_lo,
        g_hi,
        alpha=0.22,
        linewidth=0.0,
        label=f"{coverage_pct}% credible band",
    )
    ax_a.set_xlabel("Time")
    ax_a.set_ylabel(closure_label)
    ax_a.set_title("(a) A-priori closure recovery")
    ax_a.grid(True, alpha=0.25)
    ax_a.legend(loc="best", frameon=True, framealpha=0.92, edgecolor="0.8")

    # (b) A-posteriori dynamics using the training-selected closure.
    ax_b.plot(t, x_true[:, state_index], "k", lw=2, label="Truth")
    ax_b.plot(
        t,
        best["x_online"][:, state_index],
        "--",
        lw=2,
        label=best["spec"].name,
    )
    ax_b.axvspan(
        t_train[0],
        t_train[-1],
        alpha=0.10,
        label="Training window",
    )
    ax_b.set_xlabel("Time")
    ax_b.set_ylabel(state_label)
    ax_b.set_title("(b) A-posteriori reduced dynamics")
    ax_b.grid(True, alpha=0.25)
    ax_b.legend(loc="best", frameon=True, framealpha=0.92, edgecolor="0.8")

    if best_test is None:
        ax_c.text(
            0.5,
            0.5,
            "Selected model unavailable\non independent trajectory",
            ha="center",
            va="center",
            transform=ax_c.transAxes,
        )
        ax_d.text(
            0.5,
            0.5,
            "Selected model unavailable\non independent trajectory",
            ha="center",
            va="center",
            transform=ax_d.transAxes,
        )
    else:
        # (c) Independent-trajectory resolved-state PDF.
        centers, pdf_truth, pdf_model = _common_pdf_curves(
            x_true_test[:, state_index],
            best_test["x_online"][:, state_index],
        )
        ax_c.plot(centers, pdf_truth, lw=2, label="Truth")
        ax_c.plot(
            centers,
            pdf_model,
            "--",
            lw=2,
            label=best_test["spec"].name,
        )
        ax_c.set_xlabel("Resolved state")
        ax_c.set_ylabel("Probability density")
        ax_c.set_title("(c) Independent-trajectory PDF")
        ax_c.grid(True, alpha=0.25)
        ax_c.legend(loc="best", frameon=True, framealpha=0.92, edgecolor="0.8")

        # (d) Independent-trajectory PSD from stored evaluation data.
        long_time = best_test["evaluation"]["long_time"]
        freq = np.asarray(long_time["psd_frequency"])
        psd_truth = np.asarray(long_time["psd_reference"])
        psd_model = np.asarray(long_time["psd_prediction"])

        tiny = np.finfo(float).tiny
        ax_d.semilogy(freq, np.maximum(psd_truth, tiny), lw=2, label="Truth")
        ax_d.semilogy(
            freq,
            np.maximum(psd_model, tiny),
            "--",
            lw=2,
            label=best_test["spec"].name,
        )
        ax_d.set_xlabel("Frequency")
        ax_d.set_ylabel("PSD")
        ax_d.set_title("(d) Independent-trajectory PSD")
        ax_d.grid(True, alpha=0.25)
        ax_d.legend(loc="best", frameon=True, framealpha=0.92, edgecolor="0.8")

    # fig.suptitle(
    #     f"Bayesian closure verification: {display_name}",
    #     fontsize=18,
    #     y=0.995,
    # )
    fig.tight_layout(rect=(0.0, 0.0, 1.0, 0.965), pad=1.4, w_pad=1.6, h_pad=2.0)

    if save_figure:
        out = Path("results/linear/"+output_name) 
        fig.savefig(out, dpi=400, bbox_inches="tight")
        print(f"Saved manuscript figure: {out.resolve()}")

    _print_metric_summary(best, best_test)
    plt.show()


def main():
    filename = "closure_analysis_results_linear.pkl"
    if not os.path.exists(filename):
        print(f"\n{filename} does not exist. Nothing to plot.")
        return
    plot_linear_results(filename)


if __name__ == "__main__":
    main()
