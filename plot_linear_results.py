"""Publication-focused plots for the linear slow-fast closure problem.

This script is intentionally separate from the Lorenz-63 and two-level
Lorenz-96 plotting scripts so that the linear verification case can emphasize:

1. posterior closure recovery and uncertainty,
2. a-posteriori reduced dynamics,
3. independent-trajectory PDF agreement, and
4. independent-trajectory spectral agreement.

Expected input: ``closure_analysis_results_linear.pkl`` generated by the
unified closure-analysis pipeline.
"""

from __future__ import annotations

